func TestM56_TP_HTTP_NEW_and_REPLAY_WithZeroQuota(t *testing.T) {
	now := time.Date(2026, 8, 25, 12, 0, 0, 0, time.UTC)
	tc := newM56HTTPFixture(t, now)

	tpID := "test-tp-temporary-principal"
	tp := &domain.TemporaryPrincipal{
		TemporaryPrincipalID: tpID,
		PartnerID:            "P1",
		Status:               domain.TPStatusActive,
		ExpiresAt:            now.Add(time.Hour),
		MaxSubmissions:       1,
		CommittedSubmissions: 0,
	}
	tc.store.SeedTemporaryPrincipal(tp)

	reqBody := `{"partner_id":"P1","agent":{"platform":"windows","version":"1.0"},"claimed_device":{"hostname":"node-m56-tp"}}`

	// 1. HTTP NEW
	rr1 := doAuth(t, tc.handler, "POST", "/v1/pre-onboarding-requests", reqBody, map[string]string{
		"Authorization": "Bearer tok-temporary-principal", "Content-Type": "application/json",
		"Idempotency-Key":  "m56-tp-integration-key-1",
		"X-Correlation-ID": "corr-tp-1",
	})

	if rr1.Code != http.StatusCreated {
		t.Fatalf("expected 201 Created, got %d. Body: %s", rr1.Code, rr1.Body.String())
	}

	var resp1 openapi.PreOnboardingCreateResponse
	if err := json.Unmarshal(rr1.Body.Bytes(), &resp1); err != nil {
		t.Fatal(err)
	}

	if resp1.PreOnboardingRequestId == "" {
		t.Fatal("expected non-empty pre_onboarding_request_id")
	}
	if string(resp1.PartnerId) != "P1" {
		t.Fatalf("expected partner P1, got %s", resp1.PartnerId)
	}

	etag1 := rr1.Header().Get("ETag")
	loc1 := rr1.Header().Get("Location")

	// Verify quota is consumed
	uow, _ := tc.store.Begin(context.Background())
	tpRec, _, _ := uow.TemporaryPrincipalStore().Get(context.Background(), tpID)
	uow.Rollback(context.Background())
	if tpRec.CommittedSubmissions != 1 {
		t.Fatalf("expected quota consumed to 1, got %d", tpRec.CommittedSubmissions)
	}

	// 2. HTTP REPLAY with zero remaining quota
	rr2 := doAuth(t, tc.handler, "POST", "/v1/pre-onboarding-requests", reqBody, map[string]string{
		"Authorization": "Bearer tok-temporary-principal", "Content-Type": "application/json",
		"Idempotency-Key":  "m56-tp-integration-key-1",
		"X-Correlation-ID": "corr-tp-2",
	})

	if rr2.Code != http.StatusCreated {
		t.Fatalf("expected 201 Created on replay, got %d. Body: %s", rr2.Code, rr2.Body.String())
	}

	var resp2 openapi.PreOnboardingCreateResponse
	if err := json.Unmarshal(rr2.Body.Bytes(), &resp2); err != nil {
		t.Fatal(err)
	}

	if resp2.PreOnboardingRequestId != resp1.PreOnboardingRequestId {
		t.Fatal("id mismatch on replay")
	}
	if resp2.RequestAccessToken != resp1.RequestAccessToken {
		t.Fatal("token mismatch on replay")
	}
	if rr2.Header().Get("ETag") != etag1 {
		t.Fatal("ETag mismatch on replay")
	}
	if rr2.Header().Get("Location") != loc1 {
		t.Fatal("Location mismatch on replay")
	}
	if rr2.Header().Get("X-Correlation-ID") != "corr-tp-2" {
		t.Fatal("Correlation-ID mismatch on replay")
	}

	// Verify quota remains 1
	uow, _ = tc.store.Begin(context.Background())
	tpRec, _, _ = uow.TemporaryPrincipalStore().Get(context.Background(), tpID)
	uow.Rollback(context.Background())
	if tpRec.CommittedSubmissions != 1 {
		t.Fatalf("expected quota to remain 1, got %d", tpRec.CommittedSubmissions)
	}

	// Verify Authenticator works on the returned token
	auth := capability.NewRequestAccessAuthenticator(tc.verifier, tc.store, tc.clock)
	gotAuth := auth.Authenticate(context.Background(), &authruntime.Credential{BearerToken: resp1.RequestAccessToken})
	if gotAuth.Decision != authruntime.DecisionAuthenticated {
		t.Fatalf("expected Authenticated, got %v", gotAuth.Decision)
	}

	// 3. Disable TP and verify replay fails
	tp.Status = domain.TPStatusDisabled
	tc.store.SeedTemporaryPrincipal(tp)

	rr3 := doAuth(t, tc.handler, "POST", "/v1/pre-onboarding-requests", reqBody, map[string]string{
		"Authorization": "Bearer tok-temporary-principal", "Content-Type": "application/json",
		"Idempotency-Key":  "m56-tp-integration-key-1",
		"X-Correlation-ID": "corr-tp-3",
	})

	if rr3.Code != http.StatusForbidden {
		t.Fatalf("expected 403 Forbidden on disabled TP, got %d. Body: %s", rr3.Code, rr3.Body.String())
	}
}

type syncUOW struct {
	preonboardingapp.UnitOfWork
	beforeCommit func()
}

func (s *syncUOW) Commit(ctx context.Context) error {
	if s.beforeCommit != nil {
		s.beforeCommit()
	}
	return s.UnitOfWork.Commit(ctx)
}

func TestM56_TP_HTTP_InProgress(t *testing.T) {
	now := time.Date(2026, 8, 25, 12, 0, 0, 0, time.UTC)
	tc := newM56HTTPFixture(t, now)

	tpID := "test-tp-temporary-principal"
	tp := &domain.TemporaryPrincipal{
		TemporaryPrincipalID: tpID,
		PartnerID:            "P1",
		Status:               domain.TPStatusActive,
		ExpiresAt:            now.Add(time.Hour),
		MaxSubmissions:       2,
		CommittedSubmissions: 0,
	}
	tc.store.SeedTemporaryPrincipal(tp)

	reqBody := `{"partner_id":"P1","agent":{"platform":"windows","version":"1.0"},"claimed_device":{"hostname":"node-m56-tp-in-progress"}}`

	blockCommit := make(chan struct{})
	doneCommit := make(chan struct{})
	tc.uowManagerMock.onBegin = func(uow preonboardingapp.UnitOfWork) preonboardingapp.UnitOfWork {
		return &syncUOW{
			UnitOfWork: uow,
			beforeCommit: func() {
				close(doneCommit)
				<-blockCommit
			},
		}
	}

	var wg sync.WaitGroup
	wg.Add(1)
	go func() {
		defer wg.Done()
		doAuth(t, tc.handler, "POST", "/v1/pre-onboarding-requests", reqBody, map[string]string{
			"Authorization": "Bearer tok-temporary-principal", "Content-Type": "application/json",
			"Idempotency-Key":  "m56-tp-in-progress-key",
			"X-Correlation-ID": "corr-tp-ip-1",
		})
	}()

	<-doneCommit

	// Now try another request with the same key while the first is in progress
	rr := doAuth(t, tc.handler, "POST", "/v1/pre-onboarding-requests", reqBody, map[string]string{
		"Authorization": "Bearer tok-temporary-principal", "Content-Type": "application/json",
		"Idempotency-Key":  "m56-tp-in-progress-key",
		"X-Correlation-ID": "corr-tp-ip-2",
	})

	if rr.Code != http.StatusServiceUnavailable {
		t.Fatalf("expected 503 Service Unavailable for in-progress request, got %d", rr.Code)
	}
	assertProblem(t, rr, http.StatusServiceUnavailable, "DEPENDENCY_UNAVAILABLE")

	close(blockCommit)
	wg.Wait()

	// Verify quota is exactly 1 (only the first completed successfully, the second did not execute/increment quota)
	uow, _ := tc.store.Begin(context.Background())
	tpRec, _, _ := uow.TemporaryPrincipalStore().Get(context.Background(), tpID)
	uow.Rollback(context.Background())
	if tpRec.CommittedSubmissions != 1 {
		t.Fatalf("expected CommittedSubmissions to be 1, got %d", tpRec.CommittedSubmissions)
	}
}
