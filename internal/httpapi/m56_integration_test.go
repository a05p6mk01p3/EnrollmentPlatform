type faultyProtector struct {
	failSeal bool
	openErr  error
	opens    int // counts Open invocations (replay recovery boundary)
	real     runtime.Protector
}

func (f *faultyProtector) Seal(ctx context.Context, p []byte, a []byte) (*runtime.ProtectedEnvelope, error) {
	if f.failSeal {
		return nil, runtime.ErrUnusableProtector
	}
	return f.real.Seal(ctx, p, a)
}

func (f *faultyProtector) Open(ctx context.Context, e *runtime.ProtectedEnvelope, a []byte) ([]byte, error) {
	f.opens++
	if f.openErr != nil {
		return nil, f.openErr
	}
	return f.real.Open(ctx, e, a)
}

type faultyUoW struct {
	real preonboardingapp.UnitOfWork
	fail bool
}

func (f *faultyUoW) Repository() preonboardingapp.Repository   { return f.real.Repository() }
func (f *faultyUoW) ResultStore() preonboardingapp.ResultStore { return f.real.ResultStore() }
func (f *faultyUoW) AuditWriter() preonboardingapp.AuditWriter { return f.real.AuditWriter() }
func (f *faultyUoW) IdempotencyStore() runtime.Store           { return f.real.IdempotencyStore() }
func (f *faultyUoW) RequestAccessWriter() preonboardingapp.RequestAccessWriter {
	return f.real.RequestAccessWriter()
}
func (f *faultyUoW) TemporaryPrincipalStore() preonboardingapp.TemporaryPrincipalStore {
	return f.real.TemporaryPrincipalStore()
}
func (f *faultyUoW) Commit(ctx context.Context) error {
	if f.fail {
		f.real.Rollback(ctx)
		return errors.New("injected outer UoW commit failure")
	}
	return f.real.Commit(ctx)
}
func (f *faultyUoW) Rollback(ctx context.Context) error { return f.real.Rollback(ctx) }

type faultyUoWManager struct {
	real       preonboardingapp.UnitOfWorkManager
	failCommit bool
	onBegin    func(preonboardingapp.UnitOfWork) preonboardingapp.UnitOfWork
}

func (f *faultyUoWManager) Begin(ctx context.Context) (preonboardingapp.UnitOfWork, error) {
	uow, err := f.real.Begin(ctx)
	if err != nil {
		return nil, err
	}
	if f.onBegin != nil {
		return f.onBegin(uow), nil
	}
	return &faultyUoW{real: uow, fail: f.failCommit}, nil
}

