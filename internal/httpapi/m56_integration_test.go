func TestM56_HumanOIDC_HTTP_NEW_and_REPLAY(t *testing.T) {
	tc := newM56HTTPFixture(t, time.Now())

	reqBody := `{"partner_id":"P1","agent":{"platform":"windows","version":"1.0"},"claimed_device":{"hostname":"node-m56"}}`

	// HTTP NEW
	rr1 := doAuth(t, tc.handler, "POST", "/v1/pre-onboarding-requests", reqBody, map[string]string{
		"Authorization": "Bearer tok-human-oidc", "Content-Type": "application/json",
		"Idempotency-Key":  "m56-integration-key-1",
		"X-Correlation-ID": "corr-1",
	})

	if rr1.Code != http.StatusCreated {
		t.Fatalf("expected 201 Created, got %d. Body: %s", rr1.Code, rr1.Body.String())
	}

	var resp1 openapi.PreOnboardingCreateResponse
	if err := json.Unmarshal(rr1.Body.Bytes(), &resp1); err != nil {
		t.Fatal(err)
	}

	if resp1.PreOnboardingRequestId == "" {
		t.Fatal("expected non-empty pre_onboarding_request_id")
	}
	if resp1.Status != openapi.PreOnboardingCreateResponseStatusPENDINGAPPROVAL {
		t.Fatalf("expected PENDING_APPROVAL, got %s", resp1.Status)
	}
	if string(resp1.PartnerId) != "P1" {
		t.Fatalf("expected partner P1, got %s", resp1.PartnerId)
	}
	if resp1.RequestAccessToken != "m56-integration-token-plaintext" {
		t.Fatalf("expected correct plaintext token, got %s", resp1.RequestAccessToken)
	}

	etag1 := rr1.Header().Get("ETag")
	if etag1 == "" {
		t.Fatal("expected non-empty ETag")
	}
	loc1 := rr1.Header().Get("Location")
	if loc1 != "/v1/pre-onboarding-requests/"+string(resp1.PreOnboardingRequestId) {
		t.Fatalf("expected correct Location, got %s", loc1)
	}
	if rr1.Header().Get("X-Correlation-ID") != "corr-1" {
		t.Fatalf("expected corr-1, got %s", rr1.Header().Get("X-Correlation-ID"))
	}

	// Verify Authenticator
	auth := capability.NewRequestAccessAuthenticator(tc.verifier, tc.store, tc.clock)
	gotAuth := auth.Authenticate(context.Background(), &authruntime.Credential{BearerToken: resp1.RequestAccessToken})
	if gotAuth.Decision != authruntime.DecisionAuthenticated {
		t.Fatalf("expected Authenticated, got %v", gotAuth.Decision)
	}
	b, ok := gotAuth.Binding.RequestAccess()
	if !ok || b.PreOnboardingRequestID != string(resp1.PreOnboardingRequestId) {
		t.Fatalf("expected matching binding, got %+v", b)
	}

	// HTTP REPLAY
	rr2 := doAuth(t, tc.handler, "POST", "/v1/pre-onboarding-requests", reqBody, map[string]string{
		"Authorization": "Bearer tok-human-oidc", "Content-Type": "application/json",
		"Idempotency-Key":  "m56-integration-key-1",
		"X-Correlation-ID": "corr-2",
	})

	if rr2.Code != http.StatusCreated {
		t.Fatalf("expected 201 Created on replay, got %d. Body: %s", rr2.Code, rr2.Body.String())
	}

	var resp2 openapi.PreOnboardingCreateResponse
	if err := json.Unmarshal(rr2.Body.Bytes(), &resp2); err != nil {
		t.Fatal(err)
	}

	if resp2.PreOnboardingRequestId != resp1.PreOnboardingRequestId {
		t.Fatal("id mismatch on replay")
	}
	if resp2.RequestAccessToken != resp1.RequestAccessToken {
		t.Fatal("token mismatch on replay")
	}
	if rr2.Header().Get("ETag") != etag1 {
		t.Fatal("ETag mismatch on replay")
	}
	if rr2.Header().Get("Location") != loc1 {
		t.Fatal("Location mismatch on replay")
	}
	if rr2.Header().Get("X-Correlation-ID") != "corr-2" {
		t.Fatal("Correlation-ID mismatch on replay")
	}

	if tc.tokens.calls != 1 {
		t.Fatalf("expected exactly 1 token generation, got %d", tc.tokens.calls)
	}
}

func TestM56_SealFailure_Atomicity(t *testing.T) {
	tc := newM56HTTPFixture(t, time.Now())
	tc.protector.failSeal = true

	reqBody := `{"partner_id":"P1","agent":{"platform":"windows","version":"1.0"},"claimed_device":{"hostname":"node-m56"}}`

	rr := doAuth(t, tc.handler, "POST", "/v1/pre-onboarding-requests", reqBody, map[string]string{
		"Authorization": "Bearer tok-human-oidc", "Content-Type": "application/json",
		"Idempotency-Key":  "m56-integration-seal",
		"X-Correlation-ID": "corr-seal",
	})

	assertProblem(t, rr, http.StatusServiceUnavailable, "DEPENDENCY_UNAVAILABLE")

	// Verify rollback
	key, _ := tc.verifier.Derive(authpolicy.CredentialKindRequestAccessToken, "m56-integration-token-plaintext")
	if _, err := tc.store.LookupRequestAccess(context.Background(), key); err == nil {
		t.Fatal("verifier leaked on seal failure")
	}
}

